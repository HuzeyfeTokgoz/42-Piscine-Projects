void	ft_sort_int_tab(int *tab, int size)
{
	int	i;
	int	tmp;

	while (0 <= size)
	{
		i = 0;
		while (i < size -1)
		{
			if (tab[i] > tab[i + 1])
			{
				tmp = tab[i];
				tab[i] = tab[i + 1];
				tab[i + 1] = tmp;
			}
			i++;
		}
		size--;
	}
}
